function [eqBlock, noiseVar_eq] = mmse_equalizer(rxBlock, H_freq, N0)
% MMSE_EQUALIZER Посимвольный частотный MMSE эквалайзер + АРУ
% Вход:
%   rxBlock  - принятый OFDM символ (вектор-столбец длины fft_size)
%   H_freq   - частотная характеристика канала (вектор-столбец той же длины)
%   N0       - дисперсия аддитивного белого шума (скаляр)
% Выход:
%   eqBlock      - эквализованный OFDM символ (вектор-столбец)
%   noiseVar_eq  - дисперсия шума после эквалайзера для каждой поднесущей (вектор той же длины)

    rx = rxBlock(:);
    H = H_freq(:);
    
    % Коэффициенты MMSE
    W = conj(H) ./ (abs(H).^2 + N0);
    
    % Эквализация
    eqBlock = rx .* W;
    
    % Дисперсия шума после эквалайзера для каждой поднесущей
    noiseVar_eq = N0 * abs(W).^2;
end