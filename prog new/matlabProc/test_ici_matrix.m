function test_ici_matrix()
    %% 1. ИСХОДНЫЕ НАСТРОЙКИ
    clear; clc; close all;
    addpath('C:\Users\a.blagodatin\Desktop\temp\diploma\blocks\');
    
    fprintf('==================================================\n');
    fprintf('       ЗАПУСК ТЕСТА МАТРИЦЫ ИНТЕРФЕРЕНЦИИ ICI     \n');
    fprintf('==================================================\n\n');
    
    fft_size = 2048;
    alpha_D = 0;    % Доплер сдвинут на 25% от разноса поднесущих
    epsilon = 8e3 / 3e8;    % Небольшой уход тактовой частоты
    
    %% 2. ГЕНЕРАЦИЯ МАТРИЦЫ
    I = ici_matrix_gen(fft_size, alpha_D, epsilon);
    
    %% 3. ВЕРИФИКАЦИЯ МАТЕМАТИЧЕСКИХ СВОЙСТВ
    fprintf('Параметры теста:\n');
    fprintf('  Размер матрицы: %s\n', mat2str(size(I)));
    fprintf('  Сдвиг Доплера alpha_D: %.2f\n', alpha_D);
    fprintf('  Ошибка тактовой частоты epsilon: %g\n', epsilon);
    fprintf('--------------------------------------------------\n');
    
    % Проверка 1: Энергетический баланс (Унитарность)
    % В идеальной системе без потерь в космосе энергия должна сохраняться
    mean_row_energy = mean(sum(abs(I).^2, 2));
    fprintf('[ВЕРИФИКАЦИЯ 1] Средняя энергия строк матрицы: %.4f (Ожидается 1.0000)\n', mean_row_energy);
    
    % Проверка 2: Наличие Доплеровского сдвига энергии
    % При alpha_D = 0 максимальная энергия лежит строго на главной диагонали.
    % При значении 0.25 максимум сместится, а соседние элементы начнут забирать мощность.
    [max_val, max_idx] = max(abs(I(10, :)));
    fprintf('[ВЕРИФИКАЦИЯ 2] Для 10-й поднесущей пик интерференции пришелся на поднесущую: %d\n', max_idx);
    fprintf('                Амплитуда пика: %.4f, Амплитуда соседей: %.4f\n', max_val, abs(I(10, 11)));
    
    if abs(mean_row_energy - 1) < 1e-4
        fprintf('\n[УСПЕХ] Матрица ICI сгенерирована корректно и нормирована по энергии.\n');
    else
        fprintf('\n[ОШИБКА] Нарушена нормировка или математика sinc-функции.\n');
    end
    
    %% 4. ТРЕХМЕРНАЯ ВИЗУАЛИЗАЦИЯ ДЛЯ ТЕКСТА ДИПЛОМА
    figure('Color', 'w');
    
    % Строим красивую 3D карту распределения модулей коэффициентов ICI
    mesh(0:fft_size-1, 0:fft_size-1, abs(I));
    view(-25, 45); % Разворачиваем камеру под красивым углом
    
    title(sprintf('Матрица ICI | Модули коэффициентов | \\alpha_D = %.2f, \\epsilon = %g', alpha_D, epsilon));
    xlabel('Излучаемые поднесущие (k)');
    ylabel('Принимаемые поднесущие (n)');
    zlabel('|I[n,k]|');
    colorbar; % Добавляем цветовую шкалу уровней интерференции
    
    fprintf('==================================================\n');
end
